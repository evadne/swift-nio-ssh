    /// The encoding of a host certificate for `hostKey`, written by hand so that it can hold what ``NIOSSH`` does
    /// not write. Nobody signed it: ``NIOSSH`` does not validate certificates during key exchange.
    private func encodedHostCertificate(
        for hostKey: NIOSSHPrivateKey,
        keyID: [UInt8] = Array("test host".utf8),
        extensions: [String] = [],
        reserved: [UInt8] = [],
        signatureKey: ByteBuffer? = nil,
        signature: ByteBuffer? = nil
    ) -> ByteBuffer {
        var unknownSignatureKey = ByteBuffer()
        unknownSignatureKey.writeSSHString("unknown-key@example.com".utf8)
        unknownSignatureKey.writeSSHString([1, 2, 3, 4])
        unknownSignatureKey.writeInteger(UInt8(5))

        var unknownSignature = ByteBuffer()
        unknownSignature.writeSSHString("unknown-signature@example.com".utf8)
        unknownSignature.writeSSHString([6, 7, 8, 9])

        var buffer = ByteBuffer()
        buffer.writeSSHString("ssh-ed25519-cert-v01@openssh.com".utf8)
        buffer.writeSSHString(Array(repeating: UInt8(0x21), count: 32))
        buffer.writePublicKeyWithoutPrefix(hostKey.publicKey)
        buffer.writeInteger(UInt64(7))
        buffer.writeInteger(NIOSSHCertifiedPublicKey.CertificateType.host.rawValue)
        buffer.writeSSHString(keyID)
        buffer.writeCompositeSSHString { $0.writeSSHString("host.example.com".utf8) }
        buffer.writeInteger(UInt64(0))
        buffer.writeInteger(UInt64.max)
        buffer.writeSSHString([])
        buffer.writeCompositeSSHString { buffer in
            extensions.reduce(0) { $0 + buffer.writeSSHString($1.utf8) + buffer.writeSSHString([]) }
        }
        buffer.writeSSHString(reserved)
        buffer.writeSSHString((signatureKey ?? unknownSignatureKey).readableBytesView)
        buffer.writeSSHString((signature ?? unknownSignature).readableBytesView)
        return buffer
    }
