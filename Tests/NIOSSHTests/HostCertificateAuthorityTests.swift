/// What a thread made of the work that it was given.
private final class ThreadOutcome<Value: Sendable>: @unchecked Sendable {
    // The thread writes this once, before it says that it has finished. Nothing reads it until then.
    var result: Result<Value, any Error>?
}

final class HostCertificateAuthorityTests: XCTestCase {
    private final class RecordingHostKeysDelegate: NIOSSHClientServerAuthenticationDelegate {
        var hostKeys: [NIOSSHPublicKey] = []

        func validateHostKey(hostKey: NIOSSHPublicKey, validationCompletePromise: EventLoopPromise<Void>) {
            self.hostKeys.append(hostKey)
            validationCompletePromise.succeed(())
        }
    }

    /// The encoding of a key in the OpenSSH public key format: what its base64 holds.
    private func encoding(ofOpenSSHPublicKey key: String) throws -> ByteBuffer {
        let base64 = try XCTUnwrap(key.split(separator: " ").dropFirst().first)
        return ByteBuffer(bytes: try XCTUnwrap(Data(base64Encoded: String(base64))))
    }

    private func encoding(of key: NIOSSHPublicKey) -> ByteBuffer {
        var buffer = ByteBuffer()
        buffer.writeSSHHostKey(key)
        return buffer
    }

    /// Runs a key exchange between a client ``NIOSSHHandler`` and a server that presents `encodedHostKey` and
    /// signs with `hostKey`.
    ///
    /// - returns: The messages that the client sent once the server had sent its new keys message.
    private func exchangeKeys(
        presenting encodedHostKey: ByteBuffer,
        signingWith hostKey: NIOSSHPrivateKey,
        delegate: RecordingHostKeysDelegate,
        advertiseHostCertificateAlgorithms: Bool = true
    ) throws -> [SSHMessage] {
        let server = try ScriptedServer {
            $0.serverAuthDelegate = delegate
            $0.advertiseHostCertificateAlgorithms = advertiseHostCertificateAlgorithms
        }
        server.hostKey = hostKey
        server.encodedHostKey = encodedHostKey
        server.keyExchange.hostKeyAlgorithms = ["ssh-ed25519-cert-v01@openssh.com", "ssh-ed25519"]

        try server.exchangeKeys(clientMessage: try server.exchangeVersions())
        return try server.clientMessages()
    }

    func testKeyExchangeWithHostCertificateSignedByRSAAuthority() throws {
        for certificate in Fixtures.signedByRSAAuthority {
            let delegate = RecordingHostKeysDelegate()
            let presented = try self.encoding(ofOpenSSHPublicKey: certificate)

            let sent = try self.exchangeKeys(
                presenting: presented,
                signingWith: try Fixtures.hostPrivateKey,
                delegate: delegate
            )

            // The key exchange completed: the client took the new keys into use and went on to authenticate.
            XCTAssertEqual(sent.first, .newKeys)

            // The delegate is given the certificate, and it is byte for byte what the server presented.
            XCTAssertEqual(delegate.hostKeys.count, 1)
            let hostKey = try XCTUnwrap(delegate.hostKeys.first)
            XCTAssertEqual(self.encoding(of: hostKey), presented)
            XCTAssertEqual(String(openSSHPublicKey: hostKey), certificate)
            XCTAssertEqual(
                NIOSSHCertifiedPublicKey(hostKey)?.key,
                try NIOSSHPublicKey(openSSHPublicKey: Fixtures.hostKey)
            )
        }
    }

    func testKeyExchangeWithHostCertificateSignedByECDSAAuthority() throws {
        let delegate = RecordingHostKeysDelegate()
        let presented = try self.encoding(ofOpenSSHPublicKey: Fixtures.signedWithECDSA)

        let sent = try self.exchangeKeys(
            presenting: presented,
            signingWith: try Fixtures.hostPrivateKey,
            delegate: delegate
        )

        XCTAssertEqual(sent.first, .newKeys)
        XCTAssertEqual(delegate.hostKeys.count, 1)
        let hostKey = try XCTUnwrap(delegate.hostKeys.first)
        XCTAssertEqual(self.encoding(of: hostKey), presented)
        XCTAssertEqual(String(openSSHPublicKey: hostKey), Fixtures.signedWithECDSA)
    }

    func testKeyExchangeWithHostCertificateSignedByAuthorityOfAnUnknownKind() throws {
        let delegate = RecordingHostKeysDelegate()
        let hostKey = NIOSSHPrivateKey(ed25519Key: .init())
        let presented = self.encodedHostCertificate(for: hostKey)

        let sent = try self.exchangeKeys(presenting: presented, signingWith: hostKey, delegate: delegate)

        XCTAssertEqual(sent.first, .newKeys)
        XCTAssertEqual(delegate.hostKeys.count, 1)
        let presentedHostKey = try XCTUnwrap(delegate.hostKeys.first)
        XCTAssertEqual(self.encoding(of: presentedHostKey), presented)
        XCTAssertEqual(NIOSSHCertifiedPublicKey(presentedHostKey)?.key, hostKey.publicKey)
    }

    func testKeyExchangeWithHostCertificateSignedWithAnUnknownAlgorithmByAKnownKey() throws {
        let delegate = RecordingHostKeysDelegate()
        let hostKey = NIOSSHPrivateKey(ed25519Key: .init())
        let authority = NIOSSHPrivateKey(ed25519Key: .init()).publicKey
        let presented = self.encodedHostCertificate(for: hostKey, signatureKey: self.encoding(of: authority))

        let sent = try self.exchangeKeys(presenting: presented, signingWith: hostKey, delegate: delegate)

        XCTAssertEqual(sent.first, .newKeys)
        XCTAssertEqual(delegate.hostKeys.count, 1)
        let presentedHostKey = try XCTUnwrap(delegate.hostKeys.first)
        XCTAssertEqual(self.encoding(of: presentedHostKey), presented)
        XCTAssertEqual(NIOSSHCertifiedPublicKey(presentedHostKey)?.signatureKey, authority)
    }

    func testHostCertificateSignedByAuthorityOfAnUnknownKindIsRejectedWhenTheServerDoesNotHoldItsKey() throws {
        let delegate = RecordingHostKeysDelegate()
        let presented = try self.encoding(ofOpenSSHPublicKey: Fixtures.signedWithRSASHA512)

        XCTAssertThrowsError(
            try self.exchangeKeys(
                presenting: presented,
                signingWith: NIOSSHPrivateKey(ed25519Key: .init()),
                delegate: delegate
            )
        ) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidExchangeHashSignature)
        }
        XCTAssertEqual(delegate.hostKeys, [])
    }

    func testHostCertificateSignedByAuthorityOfAnUnknownKindIsRejectedWhenNotOffered() throws {
        // The client offered no certificate algorithm, so the server may not present a certificate.
        let delegate = RecordingHostKeysDelegate()
        let presented = try self.encoding(ofOpenSSHPublicKey: Fixtures.signedWithRSASHA512)

        XCTAssertThrowsError(
            try self.exchangeKeys(
                presenting: presented,
                signingWith: try Fixtures.hostPrivateKey,
                delegate: delegate,
                advertiseHostCertificateAlgorithms: false
            )
        ) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidHostKeyForKeyExchange)
        }
        XCTAssertEqual(delegate.hostKeys, [])
    }

    func testMalformedHostCertificateIsRejectedInKeyExchange() throws {
        let hostKey = NIOSSHPrivateKey(ed25519Key: .init())

        // A signature key and a signature that do not begin with the name of their kind.
        for presented in [
            self.encodedHostCertificate(for: hostKey, signatureKey: ByteBuffer(bytes: [0, 0, 0, 9, 1])),
            self.encodedHostCertificate(for: hostKey, signatureKey: ByteBuffer()),
            self.encodedHostCertificate(for: hostKey, signature: ByteBuffer(bytes: [0, 0, 0, 9, 1])),
            self.encodedHostCertificate(for: hostKey, signature: ByteBuffer()),
        ] {
            let delegate = RecordingHostKeysDelegate()
            XCTAssertThrowsError(
                try self.exchangeKeys(presenting: presented, signingWith: hostKey, delegate: delegate)
            ) { error in
                XCTAssertEqual((error as? NIOSSHError)?.type, .invalidSSHMessage)
            }
            XCTAssertEqual(delegate.hostKeys, [])
        }
    }

    func testCertificateSignedByAuthorityOfAnUnknownKindRoundTrips() throws {
        for certificate in Fixtures.signedByRSAAuthority {
            let key = try NIOSSHPublicKey(openSSHPublicKey: certificate)
            XCTAssertEqual(String(openSSHPublicKey: key), certificate)

            var bytes = try self.encoding(ofOpenSSHPublicKey: certificate)
            XCTAssertEqual(try bytes.readSSHHostKey(), key)
            XCTAssertEqual(bytes.readableBytes, 0)
            XCTAssertEqual(self.encoding(of: key), try self.encoding(ofOpenSSHPublicKey: certificate))
        }
    }

    func testCertificateSignedByAuthorityOfAnUnknownKindHasItsFields() throws {
        let certificate = try XCTUnwrap(
            NIOSSHCertifiedPublicKey(try NIOSSHPublicKey(openSSHPublicKey: Fixtures.signedWithRSASHA512))
        )

        XCTAssertEqual(certificate.key, try NIOSSHPublicKey(openSSHPublicKey: Fixtures.hostKey))
        XCTAssertEqual(certificate.serial, 7)
        XCTAssertEqual(certificate.type, .host)
        XCTAssertEqual(certificate.keyID, "test host")
        XCTAssertEqual(certificate.validPrincipals, ["host.example.com"])
        XCTAssertEqual(certificate.validAfter, 0)
        XCTAssertEqual(certificate.validBefore, .max)
        XCTAssertEqual(certificate.criticalOptions, [:])
        XCTAssertEqual(certificate.extensions, [:])

        // The signature key is the authority's, byte for byte, though it can do nothing but be compared and written.
        XCTAssertEqual(String(openSSHPublicKey: certificate.signatureKey), Fixtures.rsaAuthority)
    }

    func testCertificatesSignedByAuthorityOfAnUnknownKindCompareByTheirBytes() throws {
        let sha512 = try NIOSSHPublicKey(openSSHPublicKey: Fixtures.signedWithRSASHA512)
        let sha256 = try NIOSSHPublicKey(openSSHPublicKey: Fixtures.signedWithRSASHA256)
        let ecdsa = try NIOSSHPublicKey(openSSHPublicKey: Fixtures.signedWithECDSA)

        XCTAssertEqual(sha512, try NIOSSHPublicKey(openSSHPublicKey: Fixtures.signedWithRSASHA512))
        XCTAssertNotEqual(sha512, sha256)
        XCTAssertNotEqual(sha512, ecdsa)
        XCTAssertEqual(Set([sha512, sha256, ecdsa, sha512]).count, 3)

        // The two were signed by the same key, with different algorithms.
        let sha512Certificate = try XCTUnwrap(NIOSSHCertifiedPublicKey(sha512))
        let sha256Certificate = try XCTUnwrap(NIOSSHCertifiedPublicKey(sha256))
        XCTAssertEqual(sha512Certificate.signatureKey, sha256Certificate.signatureKey)
        XCTAssertNotEqual(sha512Certificate.signature, sha256Certificate.signature)
        XCTAssertNotEqual(sha512Certificate.signatureKey, try XCTUnwrap(NIOSSHCertifiedPublicKey(ecdsa)).signatureKey)
    }

    func testValidationRefusesCertificateSignedByAuthorityOfAnUnknownKind() throws {
        for fixture in Fixtures.signedByRSAAuthority {
            let certificate = try XCTUnwrap(NIOSSHCertifiedPublicKey(try NIOSSHPublicKey(openSSHPublicKey: fixture)))

            // Not even when the caller names the very key that the certificate says signed it.
            for authorities in [[], [certificate.signatureKey]] {
                XCTAssertThrowsError(
                    try certificate.validate(
                        principal: "host.example.com",
                        type: .host,
                        allowedAuthoritySigningKeys: authorities
                    )
                ) { error in
                    XCTAssertEqual((error as? NIOSSHError)?.type, .invalidCertificate)
                    XCTAssertTrue(String(describing: error).contains("cannot be verified"), "\(error)")
                }
            }
        }
    }

    func testValidationRefusesCertificateSignedWithAnUnknownAlgorithmByAKnownKey() throws {
        let authority = NIOSSHPrivateKey(ed25519Key: .init()).publicKey
        var bytes = self.encodedHostCertificate(
            for: NIOSSHPrivateKey(ed25519Key: .init()),
            signatureKey: self.encoding(of: authority)
        )
        let certificate = try XCTUnwrap(NIOSSHCertifiedPublicKey(try XCTUnwrap(try bytes.readSSHHostKey())))
        XCTAssertEqual(certificate.signatureKey, authority)

        XCTAssertThrowsError(
            try certificate.validate(
                principal: "host.example.com",
                type: .host,
                allowedAuthoritySigningKeys: [authority]
            )
